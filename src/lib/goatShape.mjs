const segments = GOAT_STROKES.flatMap(points => points.slice(1).map((b,i) => {
  const a = points[i]; return { a,b,length: Math.hypot(b[0]-a[0],b[1]-a[1]) };
}));
const totalLength = segments.reduce((sum,segment) => sum+segment.length,0);
export function sampleGoat(index,count) {
  let distance = (index+.5)/count*totalLength;
  for (const { a,b,length } of segments) {
    if (distance <= length) {
      const t = distance/length;
      return [a[0]+(b[0]-a[0])*t+.14,a[1]+(b[1]-a[1])*t-.4,0];
    }
    distance -= length;
  }
  return [0,0,0];
}
